def fetch_pages(query="鐵路"):
    all_records = []

    for page in range(START_PAGE, END_PAGE + 1):
        print(f"抓取第 {page} 頁...")
        try:
            # requests 會自動處理 columns[] 這種重複參數與 URL 編碼
            resp = requests.get(
                BASE_URL,
                params={
                    "query": query,
                    "page": page,
                    "columns[]": EXTRA_COLUMNS,
                },
                timeout=15,
            )
            resp.raise_for_status()
            data = resp.json()

            records = data.get("records", [])
            all_records.extend(records)
            print(f"  取得 {len(records)} 筆，累積 {len(all_records)} 筆")

            total_pages = data.get("total_pages", END_PAGE)
            if page >= total_pages:
                print("已達最後一頁，提前結束")
                break

        except requests.exceptions.HTTPError as e:
            if resp.status_code == 403:
                print("⚠️ 收到 403，可能被 Cloudflare 阻擋，建議稍後再試或聯繫網站方")
                break
            else:
                print(f"HTTP 錯誤: {e}")
                break
        except requests.exceptions.RequestException as e:
            print(f"請求失敗: {e}")
            break

        if page < END_PAGE:
            delay = random.uniform(DELAY_MIN, DELAY_MAX)
            print(f"  等待 {delay:.1f} 秒...")
            time.sleep(delay)

    return all_records


