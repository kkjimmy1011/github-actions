import re

# ---------------------------------------------------------
# 找出字串中「括號／引號包住的區段」（含括號本身），回傳遮罩
# 涵蓋：() （） 「」 "" ''
# 目的：像「或」引出的替代名稱通常會用括號/引號包起來，
# 這類區段整段（含括號）都要移除，避免影響最長共同前綴比對
# ---------------------------------------------------------
def get_bracket_removal_mask(s: str) -> list:
    mask = [False] * len(s)
    patterns = [
        r'\([^)]*\)',   # ( ... )
        r'（[^）]*）',   # （ ... ）
        r'「[^」]*」',   # 「 ... 」
        r'"[^"]*"',     # " ... "
        r"'[^']*'",     # ' ... '
    ]
    for pat in patterns:
        for m in re.finditer(pat, s):
            for i in range(m.start(), m.end()):
                mask[i] = True
    return mask

def strip(s: str) -> str:
    # 0. 先整段移除括號/引號包住的內容（含括號本身），
    #    例如替代名稱「A(或稱B)」中的「(或稱B)」整段刪除
    bracket_mask = get_bracket_removal_mask(s)
    s = ''.join(ch for i, ch in enumerate(s) if not bracket_mask[i])

    # 先擷取開頭連續的英文/數字（保留不動）
    m = re.match(r'^[A-Za-z0-9]+', s)
    prefix = m.group(0) if m else ""
    rest = s[len(prefix):]

    # 對剩餘部分做原本的清理邏輯
    rest = re.sub(r'[A-Za-z0-9]+', '', rest)          # 去除英文、數字（規則2：開頭已保留，其餘不論前後段一律去除）
    rest = re.sub(r'[()（）\-－_/、\s]+', '', rest)     # 去除常見符號、空白
    rest = re.sub(r'」', '', rest)
    rest = re.sub(r'「', '', rest)
    rest = re.sub(r'[\'"]', '', rest)                  # 去除殘留單引號/雙引號

    result = prefix + rest
    return result



