# 金額轉換：滿千逗號分隔的英文表示法（含「元」）
# ---------------------------------------------------------
def format_amount_en(n) -> str:
    if pd.isna(n):
        return ""
    n = int(n)
    return f"{n:,}元"


# ---------------------------------------------------------
# 金額轉換：中文表示法，遇兆／億／萬才寫出（含「元」）
# 例如 1,234,000,000 -> 12億3400萬元
# ---------------------------------------------------------
def format_amount_zh(n) -> str:
    if pd.isna(n):
        return ""
    n = int(n)
    if n == 0:
        return "0元"

    parts = []
    remainder = n
    units = [("兆", 10**12), ("億", 10**8), ("萬", 10**4)]
    for name, val in units:
        if remainder >= val:
            count = remainder // val
            parts.append(f"{count}{name}")
            remainder %= val
    if remainder > 0:
        parts.append(str(remainder))

    return "".join(parts) + "元"

