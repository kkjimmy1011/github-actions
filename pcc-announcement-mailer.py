def extract_winning_companies(companies: dict) -> list:
    name_key = companies.get("name_key", {}) or {}
    winners = []
    for name, keys in name_key.items():
        for k in keys:
            # 「得標廠商」出現在 key 裡，但要排除「未得標廠商」的情況
            if "得標廠商" in k and "未得標廠商" not in k:
                winners.append(name)
                break  # 該廠商只要有任一 key 符合就算得標，不重複加入
    return winners

import re

CJK_PATTERN = re.compile(r'[\u4e00-\u9fff]')

def is_english_only(name: str) -> bool:
    """判斷名稱是否為純英文（不含任何中文字）。"""
    return bool(name) and not CJK_PATTERN.search(name)


# ---------------------------------------------------------
# 過濾 companies dict：
# - 純英文名稱的廠商，原則上刪除
# - 除非：(a) 該筆記錄所有廠商都只有英文名 -> 全部保留
#        (b) 該廠商是得標廠商 -> 保留
# 同步更新 names / ids / name_key / id_key
# ---------------------------------------------------------
def filter_companies_dict(companies: dict, winning_names: set) -> dict:
    if not companies:
        return companies

    old_names = companies.get("names", []) or []
    old_ids = companies.get("ids", []) or []
    name_key = companies.get("name_key", {}) or {}
    id_key = companies.get("id_key", {}) or {}

    if not old_names:
        return companies

    all_english_only = all(is_english_only(n) for n in old_names)

    def should_keep(n: str) -> bool:
        if not is_english_only(n):
            return True                # 含中文，一律保留
        if all_english_only:
            return True                # 全部都只有英文名，全部保留
        if n in winning_names:
            return True                # 得標廠商，即使純英文也保留
        return False                   # 其餘純英文名稱刪除

    keep_names_set = {n for n in old_names if should_keep(n)}

    new_names = [n for n in old_names if n in keep_names_set]
    new_name_key = {n: keys for n, keys in name_key.items() if n in keep_names_set}

    # ids / id_key 依「name_key 對照到的名稱是否保留」同步過濾
    # 建立 id -> 是否保留 的判斷（透過 id_key 找出該 id 對應哪些 key，
    # 再反查該 id 在 name_key 中對應的名稱是否被保留）
    # 因為原始資料沒有直接 id<->name 對照表，這裡改用「保留下來的 name_key」
    # 反查其 keys 是否與 id_key 有交集來判斷
    kept_keys = set()
    for keys in new_name_key.values():
        kept_keys.update(keys)

    new_id_key = {}
    for cid, keys in id_key.items():
        overlapped = [k for k in keys if k in kept_keys]
        if overlapped:
            new_id_key[cid] = keys

    new_ids = [cid for cid in old_ids if cid in new_id_key]

    new_companies = dict(companies)
    new_companies["names"] = new_names
    new_companies["ids"] = new_ids
    new_companies["name_key"] = new_name_key
    new_companies["id_key"] = new_id_key
    return new_companies

