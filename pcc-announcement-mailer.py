# 3. 下層明細表：每一筆招標／更正／決標各自一列，各自的日期＋金額
# ---------------------------------------------------------
def build_detail_table(df: pd.DataFrame, group_col: str = "相似組別") -> pd.DataFrame:
    money_cols = [c for c in ["預算金額", "總決標金額"] if c in df.columns]
    base_cols = [
        group_col, "date", "type", "title", "unit_name", "category",
        "company_names", "得標廠商", "開標時間", "公開閱覽日期", "pcc_url",
    ]
    cols = base_cols + money_cols

    df_detail = (
        df[[c for c in cols if c in df.columns]]
        .sort_values([group_col, "date"])
        .reset_index(drop=True)
    )
    return df_detail


# ---------------------------------------------------------
# 4. 主流程：加上分組欄位後，分別產生上層＋下層兩張表
# ---------------------------------------------------------
def build_grouped_tables(df: pd.DataFrame, title_col: str = "title", min_common_len: int = 9):
    df = df.copy()
    df["相似組別"] = group_by_similar_title(df[title_col].fillna("").tolist(), min_common_len)

    df_summary = build_summary_table(df)
    df_detail = build_detail_table(df)
    return df_summary, df_detail


