# ---------------------------------------------------------
# 判斷今天是否為「本月最後一次的週一或週五」
# 邏輯：從今天開始往後找，直到月底為止，
#      如果找不到下一個「週一或週五」，代表今天就是本月最後一次寄信日
# ---------------------------------------------------------
def is_last_send_day_of_month(today: datetime = None) -> bool:
    if today is None:
        today = datetime.now()

    # 今天必須本身就是週一(0)或週五(4)，才需要判斷是否為「最後一次」
    if today.weekday() not in (0, 4):
        return False

    # 找出本月最後一天
    if today.month == 12:
        next_month_first_day = datetime(today.year + 1, 1, 1)
    else:
        next_month_first_day = datetime(today.year, today.month + 1, 1)
    last_day_of_month = next_month_first_day - timedelta(days=1)

    # 從明天開始檢查到月底為止，是否還有下一個週一或週五
    check_date = today + timedelta(days=1)
    while check_date <= last_day_of_month:
        if check_date.weekday() in (0, 4):
            return False  # 後面還有寄信日，今天不是最後一次
        check_date += timedelta(days=1)

    return True  # 後面都沒有寄信日了，今天就是本月最後一次
